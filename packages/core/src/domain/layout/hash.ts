/**
 * 배치 해시(PLAN §4.10): 정규 JSON(키 사전순, 수는 소수 셋째 자리 고정 글, `hash` 칸 제외)의 SHA-256 앞 16자.
 * 도메인은 외부 패키지·Node `crypto`·Web Crypto(비동기)를 쓰지 않으므로 SHA-256을 직접 둔다.
 * 서버(Node)·기기(Safari·Chrome) 어디서 계산해도 같은 글이 되게 수를 고정 글로 바꾼다.
 */

export const canonicalJson = (value: unknown): string => {
  if (value === null) return 'null';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('정규 JSON에 유한하지 않은 수');
    const fixed = value.toFixed(3);
    return fixed === '-0.000' ? '0.000' : fixed;
  }
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'string') return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(canonicalJson).join(',')}]`;
  if (typeof value === 'object') {
    const entries = Object.entries(value as Record<string, unknown>)
      .filter(([k, v]) => k !== 'hash' && v !== undefined)
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
    return `{${entries.map(([k, v]) => `${JSON.stringify(k)}:${canonicalJson(v)}`).join(',')}}`;
  }
  throw new Error(`정규 JSON에 넣을 수 없는 값: ${typeof value}`);
};

